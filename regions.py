def get_region_slug(dong_name: str, dong_id: int) -> str:
    """당근마켓 URL의 in= 파라미터 값 생성: '역삼동-6035'"""
    return f"{dong_name}-{dong_id}"


def find_region(sido: str, sigungu: str, dong: str):
    """(시도, 구군, 동) → (동이름, ID) 반환"""
    sido_data = REGIONS.get(sido, {})
    sigungu_data = sido_data.get(sigungu, [])
    for name, rid in sigungu_data:
        if name == dong:
            return (name, rid)
    return None
